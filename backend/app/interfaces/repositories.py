"""Persistence ports (Dependency Inversion: services depend on these, not on SQLite/DynamoDB)."""
from typing import Iterable, Protocol

from app.domain.entities import Node, User


class UserRepository(Protocol):
    def add(self, user: User) -> User: ...

    def get_by_id(self, user_id: str) -> User | None: ...

    def get_by_username(self, username: str) -> User | None: ...

    def get_by_email(self, email: str) -> User | None: ...

    def update(self, user: User) -> User: ...

    def delete(self, user_id: str) -> None: ...


class NodeRepository(Protocol):
    def list_all(self) -> list[Node]: ...

    def get(self, node_id: str) -> Node | None: ...

    def find_author_by_author_id(self, author_id: str) -> Node | None: ...

    def create(self, node: Node) -> Node:
        """Insert a new node; raises ConflictError if node_id already exists."""
        ...

    def save(self, node: Node) -> Node:
        """Insert or replace a node."""
        ...

    def save_many(self, nodes: Iterable[Node]) -> None: ...
